import com.nickrocks.aow2bot.vision.*;
import java.io.*;
import java.nio.file.*;
import java.util.*;

/**
 * Builds Templates.java from labelled gold-counter glyphs in recording frames.
 * usage: MakeTemplates <frames dir> <labels.txt> <out Templates.java> <price rects.txt>
 * labels.txt lines: "<frame no> <glyph x> <glyph width> <char>"; plus '/' taken from the population box.
 */
public class MakeTemplates {
    public static void main(String[] a) throws Exception {
        String dir = a[0];
        Map<Character, float[]> sum = new TreeMap<>();
        Map<Character, int[]> cnt = new TreeMap<>();   // [n, sum nw]
        Map<String, Frame> cache = new LinkedHashMap<>(16, 0.75f, true) { protected boolean removeEldestEntry(Map.Entry<String, Frame> e) { return size() > 8; } };
        for (String line : Files.readAllLines(Paths.get(a[1]))) {
            String[] p = line.trim().split(" ");
            if (p.length < 4) continue;
            Frame f = cache.computeIfAbsent(p[0], k -> { try { return Img.load(dir + "/g_" + k + ".jpg"); } catch (Exception e) { throw new RuntimeException(e); } });
            int gx = Integer.parseInt(p[1]), gw = Integer.parseInt(p[2]);
            char ch = p[3].charAt(0);
            for (Ocr.Glyph g : Ocr.glyphs(f, 470, 160, 572, 189, Ocr.HUD_TEXT, 15, 30)) {
                int mid = (g.x0 + g.x1) / 2;
                if (mid >= gx && mid < gx + gw) { add(sum, cnt, ch, g); break; }
            }
        }
        // Outlined white price font (unit buttons, upgrade and tower prices): "frame x0 y0 x1 y1 text".
        Map<Character, float[]> sum2 = new TreeMap<>();
        Map<Character, int[]> cnt2 = new TreeMap<>();
        int ok = 0, bad = 0;
        for (String line : Files.readAllLines(Paths.get(a[3]))) {
            String[] p = line.trim().split(" ");
            if (p.length < 6) continue;
            Frame f = cache.computeIfAbsent(p[0], k -> { try { return Img.load(dir + "/g_" + k + ".jpg"); } catch (Exception e) { throw new RuntimeException(e); } });
            List<Ocr.Glyph> gs = Ocr.glyphs(f, Float.parseFloat(p[1]), Float.parseFloat(p[2]), Float.parseFloat(p[3]), Float.parseFloat(p[4]), Ocr.WHITE, 12, 50);
            if (gs.size() != p[5].length()) { bad++; continue; }
            ok++;
            for (int i = 0; i < gs.size(); i++) add(sum2, cnt2, p[5].charAt(i), gs.get(i));
        }
        System.err.println("price samples ok " + ok + " skipped " + bad);
        // '/' from the population box ("0/10" etc.): second glyph.
        for (int i = 1; i <= 156; i++) {
            Frame f = Img.load(String.format("%s/g_%03d.jpg", dir, i));
            List<Ocr.Glyph> gs = Ocr.glyphs(f, 485, 217, 568, 250, Ocr.HUD_TEXT, 12, 34);
            if (gs.size() == 4 && gs.get(1).nw < 12) add(sum, cnt, '/', gs.get(1));
            else if (gs.size() == 5) add(sum, cnt, '/', gs.get(2));
        }
        StringBuilder sb = new StringBuilder();
        sb.append("package com.nickrocks.aow2bot.vision;\n\n")
          .append("/** Glyph templates (14x16, hex 0-f coverage), generated by tools/desktop/MakeTemplates from the recording. */\n")
          .append("public final class Templates {\n")
          .append("    public static final class T {\n")
          .append("        public final char ch; public final int nw; public final float[] grid;\n")
          .append("        T(char ch, int nw, float[] grid) { this.ch = ch; this.nw = nw; this.grid = grid; }\n")
          .append("    }\n\n")
          .append("    private static T t(char ch, int nw, String hex) {\n")
          .append("        float[] g = new float[Ocr.GW * Ocr.GH];\n")
          .append("        for (int i = 0; i < g.length; i++) g[i] = Character.digit(hex.charAt(i), 16) / 15f;\n")
          .append("        return new T(ch, nw, g);\n")
          .append("    }\n\n")
          .append("    public static final T[] ALL = {\n");
        for (char ch : sum.keySet()) {
            float[] s = sum.get(ch); int[] c = cnt.get(ch);
            StringBuilder hex = new StringBuilder();
            for (float v : s) hex.append(Character.forDigit(Math.min(15, Math.round(v / c[0] * 15)), 16));
            int nw = Math.round((float) c[1] / c[0]);
            sb.append("        t('").append(ch).append("', ").append(nw).append(", \"").append(hex).append("\"), // ")
              .append(c[0]).append(" samples\n");
            System.err.println(ch + ": " + c[0] + " samples, nw " + nw);
        }
        for (char ch : sum2.keySet()) {
            float[] s = sum2.get(ch); int[] c = cnt2.get(ch);
            StringBuilder hex = new StringBuilder();
            for (float v : s) hex.append(Character.forDigit(Math.min(15, Math.round(v / c[0] * 15)), 16));
            int nw = Math.round((float) c[1] / c[0]);
            sb.append("        t('").append(ch).append("', ").append(nw).append(", \"").append(hex).append("\"), // price font, ")
              .append(c[0]).append(" samples\n");
            System.err.println("price " + ch + ": " + c[0] + " samples, nw " + nw);
        }
        sb.append("    };\n}\n");
        Files.write(Paths.get(a[2]), sb.toString().getBytes());
    }

    static void add(Map<Character, float[]> sum, Map<Character, int[]> cnt, char ch, Ocr.Glyph g) {
        float[] s = sum.computeIfAbsent(ch, k -> new float[Ocr.GW * Ocr.GH]);
        for (int i = 0; i < s.length; i++) s[i] += g.grid[i];
        int[] c = cnt.computeIfAbsent(ch, k -> new int[2]);
        c[0]++; c[1] += g.nw;
    }
}
